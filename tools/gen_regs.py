#!/usr/bin/env python3
"""Generate s5kc505a_regs.h from Lenovo's libmmcamera_s5kc505a.so.

Usage: python3 -I gen_regs.py libmmcamera_s5kc505a.so > s5kc505a_regs.h

Each table entry in the blob is {u16 reg, u16 val, u32 delay_ms}; a table
ends at the first {0, 0} entry. Offsets were found by scanning the .data
section (see CAMERA_FINDINGS.md).
"""
import hashlib
import struct
import sys


INIT_OFF = 0x6E20
# Mode tables 1-4 start with an 8-byte header entry {1, 0, 0}; skip it.
MODES = [
    ("2608x1960", 0x3EEE4),
    ("1304x980", 0x42EEC + 8),
]


def table(d, off):
    out = []
    while True:
        reg, val, delay = struct.unpack_from("<HHI", d, off)
        off += 8
        if reg == 0 and val == 0:
            return out
        out.append((reg, val, delay))


def emit(name, regs):
    print(f"static const struct cci_reg_sequence {name}[] = {{")
    for reg, val, delay in regs:
        if delay:
            raise SystemExit(f"{name}: unexpected delay at {reg:#06x}")
        print(f"\t{{ CCI_REG8(0x{reg:04x}), 0x{val:02x} }},")
    print("};\n")


def main():
    d = open(sys.argv[1], "rb").read()
    digest = hashlib.sha256(d).hexdigest()
    print("/* SPDX-License-Identifier: GPL-2.0-only */")
    print("/*")
    print(" * Register tables for the Samsung S5KC505A, generated by")
    print(" * camera/tools/gen_regs.py from the Lenovo CD-18781Y vendor")
    print(f" * libmmcamera_s5kc505a.so (sha256 {digest[:16]}...).")
    print(" * Do not edit by hand.")
    print(" */\n")

    init = table(d, INIT_OFF)
    # The first write (0x0a02 = 0x0f) is followed by a 10 ms delay.
    first = init[0]
    if first[2] != 10:
        raise SystemExit("init table layout changed")
    emit("s5kc505a_init_pre", [(first[0], first[1], 0)])
    emit("s5kc505a_init_regs", init[1:])

    for label, off in MODES:
        regs = table(d, off)
        # 0x0136/0x0137 (external clock) is written once in common setup.
        regs = [r for r in regs if r[0] not in (0x0136, 0x0137)]
        emit(f"s5kc505a_mode_{label}_regs", regs)


if __name__ == "__main__":
    main()
